// Turns the Iconly SVG files in src/app/shared/icons/svg into a typed registry the app-icon component reads.
// File names are "<style>-<name>.svg" (bold-success.svg, outline-arrow-right.svg). Run: npm run build:icons
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/app/shared/icons/svg/', import.meta.url);
const out = new URL('../src/app/shared/icons/icons.generated.ts', import.meta.url);
const entries = [];
const names = [];

for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(new URL(file, dir), 'utf8');
  // Older Iconly files wrap their paths in a group that only shifts them: keep that shift on each path.
  const shift = /<g\b[^>]*transform="translate\(([-\d.]+),\s*([-\d.]+)\)"/.exec(svg);
  const t = shift ? `translate(${Number(shift[1])} ${Number(shift[2])})` : '';
  const paths = [...svg.matchAll(/<path\b([^>]*)>/g)].map((m) => {
    const d = /\bd="([^"]+)"/.exec(m[1])?.[1];
    if (!d) throw new Error(`${file}: a path has no d attribute`);
    return { d, evenodd: /fill-rule="evenodd"/.test(m[1]), t };
  });
  if (!paths.length) throw new Error(`${file}: no paths (only plain path icons are supported)`);
  if (/<(circle|rect|mask|clipPath|defs)\b/.test(svg)) throw new Error(`${file}: contains shapes other than paths`);
  names.push(file.replace(/\.svg$/, ''));
  entries.push(`  ${JSON.stringify(file.replace(/\.svg$/, ''))}: [\n${paths.map((p) => `    { d: ${JSON.stringify(p.d)}, evenodd: ${p.evenodd}${p.t ? `, t: ${JSON.stringify(p.t)}` : ''} },`).join('\n')}\n  ],`);
}

writeFileSync(
  out,
  `// Generated by scripts/build-icons.mjs from the SVG files next to it. Do not edit by hand.\nexport interface IconPath { d: string; evenodd: boolean; t?: string }\n\nexport const ICONS: Record<string, IconPath[]> = {\n${entries.join('\n')}\n};\n\nexport type IconName = ${names.map((n) => JSON.stringify(n)).join(' | ')};\n`,
);
console.log(`Wrote ${entries.length} icons.`);
